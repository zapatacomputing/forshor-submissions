def test_canonical_json_is_sorted_compact_and_rejects_nan():
    assert canon.canonical_json({"b": 1, "a": [2, {"d": 1, "c": 2}]}) == '{"a":[2,{"c":2,"d":1}],"b":1}'
    try:
        canon.canonical_json({"x": float("nan")})
    except ValueError:
        pass
    else:
        raise AssertionError("NaN must not be hashable")


#: The full run's qubit text as the publisher's fixture builder wrote it into golden.json BEFORE swap 002 (it said "32 w Toffoli" and ForShor 8e37ce7).
#: golden.json is generated by that builder, not by this repo, and it has not been re-run: until it is, those two
#: strings are the only thing the golden test may not compare. When golden.json carries the current text (`mapping.PEAK_LABEL` /
#: `mapping.PEAK_RULE`) the exemption switches itself off and they are compared like everything else.
STALE_GOLDEN_TEXT = ("qubitsLabel", "qubitsRule")


def _golden_text_is_stale(expected):
    run = expected["fullRun"]
    return bool(run) and (run["qubitsLabel"], run["qubitsRule"]) != (mapping.PEAK_LABEL, mapping.PEAK_RULE)


def test_every_panel_equals_what_forshor_sites_builder_made_from_the_same_engine_view():
    for name, case in GOLDEN["cases"].items():
        expected = copy.deepcopy(case["panel"])
        got = mapping.panel_of(case["view"], epoch=GOLDEN["epoch"], row_id=case["rowId"], board=case["board"],
                               delta=case["delta"], verification=expected["verification"])
        if _golden_text_is_stale(expected):
            for doc in (got, expected):
                for key in STALE_GOLDEN_TEXT:
                    doc["fullRun"].pop(key)
        assert got == expected, name


def test_the_golden_qubit_text_is_either_current_or_exactly_the_pre_swap_002_text():
    """The exemption above covers only the old text, never an arbitrary difference."""
    run = GOLDEN["cases"]["full_submission"]["panel"]["fullRun"]
    if _golden_text_is_stale(GOLDEN["cases"]["full_submission"]["panel"]):
        assert "32 w Toffoli" in run["qubitsRule"] and "8e37ce7" in run["qubitsRule"]
        assert run["qubitsLabel"].endswith("not Lean-evaluated on this policy)")
    else:
        assert (run["qubitsLabel"], run["qubitsRule"]) == (mapping.PEAK_LABEL, mapping.PEAK_RULE)


